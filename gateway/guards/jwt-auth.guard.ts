import { ExecutionContext, Injectable } from '@nestjs/common';
import { Reflector } from '@nestjs/core';
import { AuthGuard } from '@nestjs/passport';
import { IS_PUBLIC_KEY } from '../../shared/decorators/public.decorator';

/**
 * Global JWT authentication guard. Strategy implementation lives in
 * modules/identity/presentation/strategies/jwt.strategy.ts. Routes
 * decorated with `@Public()` (see /shared/decorators/public.decorator.ts)
 * bypass authentication entirely — used for registration, login, and
 * token refresh endpoints.
 */
@Injectable()
export class JwtAuthGuard extends AuthGuard('jwt') {
  constructor(private readonly reflector: Reflector) {
    super();
  }

  canActivate(context: ExecutionContext) {
    const isPublic = this.reflector.getAllAndOverride<boolean>(IS_PUBLIC_KEY, [
      context.getHandler(),
      context.getClass(),
    ]);

    if (isPublic) {
      return true;
    }

    return super.canActivate(context);
  }
}
